// Helper to normalize title for accurate alphabetical sorting in Spanish (ignoring leading ¿, ¡, etc.)
export function getSortTitle(title: string): string {
  return title.replace(/^[¿¡"']/, '').trim();
}

// 28 canciones ordenadas ALFABÉTICAMENTE de la A a la Z
export const COLAPSO_ALPHABETICAL_SONGS: Song[] = [...COLAPSO_POSTER_SONGS]
  .sort((a, b) =>
    getSortTitle(a.title).localeCompare(getSortTitle(b.title), 'es', { sensitivity: 'base' })
  )
  .map((song, index) => ({
    ...song,
    order: index + 1,
  }));

